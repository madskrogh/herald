#!/usr/bin/env bash
# Writes .env for the current checkout so parallel worktrees don't collide:
# a compose project name of its own and a port slot of its own.
#
# The main checkout gets slot 0 (default ports). Each worktree gets the lowest
# free slot 1-9, and every published port is shifted by slot * 100.
# Compose can't do arithmetic in variable interpolation, so the ports are
# computed here and written out in full.
#
# A slot is free when no other worktree's .env holds it and Docker publishes
# none of its ports. The second check finds a stack that outlived its
# worktree. Picking a slot fails, rather than guess, when Docker can't be
# asked or another worktree can't be read.
#
# Run through `make .env` (a prerequisite of `make up`), which runs it again
# when this script changes. An existing .env keeps its project name and slot,
# so a running stack keeps its ports, and gains the ports added since.
set -euo pipefail

# Each published port's variable and its port in slot 0.
ports=(
  HERALD_POSTGRES_PORT=5432
  HERALD_NATS_PORT=4222
  HERALD_NATS_MONITOR_PORT=8222
  HERALD_API_HTTP_PORT=8080
  HERALD_API_GRPC_PORT=9090
  HERALD_API_PPROF_PORT=6060
  HERALD_DISPATCHER_PPROF_PORT=6061
  HERALD_OTLP_HTTP_PORT=4318
  HERALD_CLICKHOUSE_HTTP_PORT=8123
  HERALD_DEMO_ENDPOINT_PORT=9000
)

top=$(git rev-parse --show-toplevel)
cd "$top"

# The first entry of `git worktree list` is always the main checkout.
worktrees=$(git worktree list --porcelain | sed -n 's/^worktree //p')
main=$(head -n1 <<<"$worktrees")

# Prints the port in slot $2 of $1, an entry of $ports.
slot_port() {
  echo $((${1#*=} + $2 * 100))
}

# Succeeds if Docker publishes any of slot $1's ports. $published holds one
# published host port, or range of them (5532 or 4300-4400), per line.
slot_published() {
  local entry port lo hi
  for entry in "${ports[@]}"; do
    port=$(slot_port "$entry" "$1")
    while IFS=- read -r lo hi; do
      if [[ -n "$lo" ]] && ((port >= lo && port <= ${hi:-$lo})); then return 0; fi
    done <<<"$published"
  done
  return 1
}

slot=
project=
if [[ -f .env ]]; then
  slot=$(sed -n 's/^HERALD_SLOT=//p' .env)
  project=$(sed -n 's/^COMPOSE_PROJECT_NAME=//p' .env)
fi

if [[ -n "$slot" && -n "$project" ]]; then
  : # Keep them.
elif [[ "$top" == "$main" ]]; then
  slot=0
  project=herald
else
  # A worktree, or a .env, that exists but can't be read would hide its slot.
  # A removed worktree that git still lists doesn't exist, and holds no slot.
  used=
  while IFS= read -r wt; do
    if [[ (-e "$wt" && ! (-r "$wt" && -x "$wt")) || (-e "$wt/.env" && ! -r "$wt/.env") ]]; then
      echo "worktree-env: can't read $wt to see which slot it holds; run this where every worktree can be read" >&2
      exit 1
    fi
    if [[ -f "$wt/.env" ]]; then used+=$(sed -n 's/^HERALD_SLOT=//p' "$wt/.env")$'\n'; fi
  done <<<"$worktrees"
  # docker ps prints each container's ports as 127.0.0.1:5532->5432/tcp,
  # comma-separated; the host side is between the last ':' and '->'.
  if ! docker_ports=$(docker ps --format '{{.Ports}}'); then
    echo "worktree-env: can't list the ports Docker publishes, to find a free slot: is Docker running?" >&2
    exit 1
  fi
  published=$(grep -oE ':[0-9]+(-[0-9]+)?->' <<<"$docker_ports" | sed -E 's/^:|->$//g' || true)
  for s in 1 2 3 4 5 6 7 8 9; do
    if ! grep -qx "$s" <<<"$used" && ! slot_published "$s"; then slot=$s; break; fi
  done
  if [[ -z "$slot" ]]; then
    echo "worktree-env: all 9 slots are taken; remove a worktree, or stop a stack that outlived its worktree (docker ps)" >&2
    exit 1
  fi
  # Compose project names allow lowercase letters, digits, '-' and '_'.
  name=$(basename "$top" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9_\n-' '-')
  project="herald-$name"
fi

{
  echo "# Generated by scripts/worktree-env.sh, and rewritten in the same slot when"
  echo "# the script changes. Delete this file to regenerate it in a new slot."
  echo "COMPOSE_PROJECT_NAME=$project"
  echo "HERALD_SLOT=$slot"
  for entry in "${ports[@]}"; do
    echo "${entry%%=*}=$(slot_port "$entry" "$slot")"
  done
} >.env
echo "worktree-env: wrote .env ($project, slot $slot)"
