#!/usr/bin/env bash
# Writes .env for the current checkout so parallel worktrees don't collide:
# a compose project name of its own and a port slot of its own.
#
# The main checkout gets slot 0 (default ports). Each worktree gets the lowest
# free slot 1-9, and every published port is shifted by slot * 100.
# Compose can't do arithmetic in variable interpolation, so the ports are
# computed here and written out in full.
#
# Run through `make .env` (a prerequisite of `make up`). Does nothing if .env exists.
set -euo pipefail

top=$(git rev-parse --show-toplevel)
cd "$top"
[[ -f .env ]] && exit 0

# The first entry of `git worktree list` is always the main checkout.
worktrees=$(git worktree list --porcelain | sed -n 's/^worktree //p')
main=$(head -n1 <<<"$worktrees")

if [[ "$top" == "$main" ]]; then
  slot=0
  project=herald
else
  used=$(while IFS= read -r wt; do
    if [[ -f "$wt/.env" ]]; then sed -n 's/^HERALD_SLOT=//p' "$wt/.env"; fi
  done <<<"$worktrees")
  slot=
  for s in 1 2 3 4 5 6 7 8 9; do
    if ! grep -qx "$s" <<<"$used"; then slot=$s; break; fi
  done
  if [[ -z "$slot" ]]; then
    echo "worktree-env: all 9 slots are taken; remove a worktree first" >&2
    exit 1
  fi
  # Compose project names allow lowercase letters, digits, '-' and '_'.
  name=$(basename "$top" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9_\n-' '-')
  project="herald-$name"
fi

offset=$((slot * 100))
cat >.env <<EOF
# Generated by scripts/worktree-env.sh. Delete this file to regenerate it.
COMPOSE_PROJECT_NAME=$project
HERALD_SLOT=$slot
HERALD_POSTGRES_PORT=$((5432 + offset))
HERALD_NATS_PORT=$((4222 + offset))
HERALD_NATS_MONITOR_PORT=$((8222 + offset))
HERALD_API_HTTP_PORT=$((8080 + offset))
HERALD_API_GRPC_PORT=$((9090 + offset))
EOF
echo "worktree-env: wrote .env ($project, slot $slot)"
